export function toAiHabitIconKey(key: string | null | undefined): ValidAiHabitIconKey | null {
  if (!key) return null;
  const trimmed = key.trim().toLowerCase();
  if ((VALID_AI_HABIT_ICON_KEYS as readonly string[]).includes(trimmed)) {
    return trimmed as ValidAiHabitIconKey;
  }
  if (trimmed in LEGACY_TO_AI_KEY_MAP) {
    return LEGACY_TO_AI_KEY_MAP[trimmed];
  }
  return null;
}

